'use strict';
const fs=require('fs');
const assert=require('node:assert/strict');
const source=fs.readFileSync(__dirname+'/better-osm-runtime.js','utf8');
const start=source.indexOf('    const mapLibre = window.OSM?.MapLibre;');
const end=source.indexOf('    if (window.OSM?.MODULE_PATHS)',start);
assert(start>=0&&end>start,'language guard should be in actual runtime');
const code=source.slice(start,end);
let calls=0;
const win={OSM:{MapLibre:{setOMTMapLanguage:()=>{calls++}}}};
(new Function('window',code))(win);
const guard=win.OSM.MapLibre.setOMTMapLanguage;
guard({getStyle:()=>({metadata:{}})});
guard({getStyle:()=>{throw new Error('style is loading')}});
assert.equal(calls,0,'OpenFreeMap and a not-yet-loaded style must not use MapTiler localization');
guard({getStyle:()=>({metadata:{'maptiler:language':'en'}})});
assert.equal(calls,1,'actual MapTiler style should retain its localization');
(new Function('window',code))(win);
assert.equal(win.OSM.MapLibre.setOMTMapLanguage,guard,'guard must install once');
console.log(JSON.stringify({skip_non_maptiler:true,retain_maptiler:true,no_double_install:true}));
